"""Compile and exercise only owned memory; never load a hook DLL or touch a game."""
from pathlib import Path
import shutil
import subprocess

import pytest

ROOT = Path(__file__).resolve().parents[1]


def test_native_capture_owned_memory_contract(tmp_path):
    compiler = shutil.which('g++')
    if compiler is None:
        pytest.skip('owned C++ capture test requires g++')
    binary = tmp_path / 'owned-capture.exe'
    source = ROOT / 'native_pc/native_event_runtime'
    build = subprocess.run([compiler, '-std=c++17', '-static', '-O2', '-Wall', '-Wextra', '-Werror',
        '-I', str(source), str(ROOT / 'tests/native_capture_owned.cpp'),
        str(source / 'native_capture.cpp'), '-o', str(binary)], capture_output=True, text=True, timeout=60)
    assert build.returncode == 0, build.stdout + build.stderr
    result = subprocess.run([str(binary)], capture_output=True, text=True, timeout=10)
    assert result.returncode == 0, (result.returncode, result.stdout, result.stderr)
    assert 'owned capture:' in result.stdout
    print(result.stdout.strip())


@pytest.mark.parametrize("fixture_name,expected_fields", [("cold-plan-dbf93c8.json", 2), ("cold-plan-b91da2b.json", 3)])
def test_actual_cold_plan_and_384_owned_entities(tmp_path, fixture_name, expected_fields):
    import json
    compiler = shutil.which('g++')
    if compiler is None:
        pytest.skip('owned C++ capture test requires g++')
    # Generated by root dbf93c8 cold-plan fixture (52 nodes, depth 14), not a
    # second handwritten plan. Parser glue here is test-only initialization.
    plan = json.loads((ROOT / 'tests/fixtures/native_capture' / fixture_name).read_text())
    assert len(plan['fields']) == expected_fields
    assert len(plan['projections']) == 52
    lines = ['void load_cold_plan(HookCapturePlan& p) {',
             'p.schema_version = 1; p.max_bytes = 1048576; p.max_reads = 65536;',
             f'p.field_count = {len(plan["fields"])}; p.projection_count = {len(plan["projections"])};']
    enum_fields = {'kind': 'ProjectionKind', 'gate': 'TypeGate'}
    for i, node in enumerate(plan['projections']):
        for key, value in node.items():
            if key == 'pointer_offsets':
                lines.append(f'p.projections[{i}].depth = {len(value)};')
                lines += [f'p.projections[{i}].pointer_offsets[{j}] = {offset};' for j, offset in enumerate(value)]
                continue
            if key in enum_fields:
                value = f'{enum_fields[key]}::{value}'
            elif isinstance(value, bool):
                value = 'true' if value else 'false'
            lines.append(f'p.projections[{i}].{key} = {value};')
    role_ids = {name: i + 1 for i, name in enumerate(dict.fromkeys(field['role'] for field in plan['fields']))}
    for i, field in enumerate(plan['fields']):
        for key, value in field.items():
            if key in ('name', 'pointer_offsets'):
                continue
            if key == 'field_id':
                key = 'id'
            elif key == 'role':
                value = role_ids[value]
            elif key == 'guard_side':
                key, value = 'guard', f'Guard::{value}'
            elif key in ('phase', 'root', 'kind'):
                value = f'{dict(phase="Phase", root="Root", kind="Kind")[key]}::{value}'
            elif isinstance(value, bool):
                value = 'true' if value else 'false'
            lines.append(f'p.fields[{i}].{key} = {value};')
    lines.append('}')
    (tmp_path / 'cold_plan_fixture.inc').write_text('\n'.join(lines))
    binary = tmp_path / 'cold-capture.exe'
    source = ROOT / 'native_pc/native_event_runtime'
    build = subprocess.run([compiler, '-std=c++17', '-static', '-O2', '-Wall', '-Wextra', '-Werror',
        '-I', str(source), '-I', str(tmp_path), str(ROOT / 'tests/native_capture_cold.cpp'),
        str(source / 'native_capture.cpp'), '-o', str(binary)], capture_output=True, text=True, timeout=60)
    assert build.returncode == 0, build.stdout + build.stderr
    result = subprocess.run([str(binary)], capture_output=True, text=True, timeout=10)
    assert result.returncode == 0, (result.returncode, result.stdout, result.stderr)
    assert 'cold384:' in result.stdout
    print(result.stdout.strip())
